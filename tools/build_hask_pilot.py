OUT = ROOT / "docs" / "integration" / "hask_pilot"
FIXTURES = ROOT / "tests" / "fixtures" / "hask_pilot"
STAMP = "<!-- GENERATED by tools/build_hask_pilot.py; DO NOT EDIT -->\n"


def write_json(name: str, value: object) -> None:
    (OUT / name).write_text(json.dumps(value, indent=2, sort_keys=True, ensure_ascii=False) + "\n", encoding="utf-8")


def write_md(name: str, value: str) -> None:
    (OUT / name).write_text(STAMP + value.rstrip() + "\n", encoding="utf-8")


def trace(platform: str, result: dict) -> str:
    canonical = [item for match in result["canonical_evidence"] for item in match["canonical_ids"]]
    candidates = result["candidates"]
    return f"""# HADocs {platform.title()} Pilot Trace

- Input observations: {', '.join(item['evidence_id'] for item in result['local_evidence'])}
- Local HADocs evidence: preserved verbatim in `local_evidence`
- Canonical evidence: {', '.join(canonical) or 'no_match'}
- Matched scenarios: {', '.join(sorted({item for candidate in candidates for item in candidate['scenarios']}))}
- Candidate root causes: {', '.join(item['candidate_id'] for item in candidates)}
- Competing causes: {', '.join(sorted({item for candidate in candidates for item in candidate['competing_causes']}))}
- Supporting evidence: {', '.join(sorted({item for candidate in candidates for item in candidate['supporting_canonical_evidence']}))}
- Contradicting evidence: none supplied by local pilot fixture
- Missing evidence: {', '.join(sorted({item for candidate in candidates for item in candidate['missing_evidence']}))}
- Recommendations: {', '.join(sorted({item for candidate in candidates for item in candidate['recommendations']}))}
- Verification: {', '.join(sorted({item for candidate in candidates for item in candidate['verification']}))}
- Provenance: {', '.join(sorted({item for candidate in candidates for item in candidate['provenance']}))}
- Conflicts preserved: {sum(len(item['conflicts']) for item in candidates)}
- Known gaps preserved: {sum(len(item['known_gaps']) for item in candidates)}
- Final pilot status: `{result['status']}`
- Confirmed candidates: none
- Health Score impact: none
"""



        local = json.loads((FIXTURES / f"{platform}_local_evidence.json").read_text(encoding="utf-8"))
        results[platform] = run_pilot(platform, local, config)
        write_json(f"HADOCS_{platform.upper()}_PILOT_RESULT.json", results[platform])
